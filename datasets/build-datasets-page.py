#!/usr/bin/env python3
"""Generate docs/datasets/index.html from datasets/README.md.

NOTICE: this file was largely written by an LLM (Claude Code).

datasets/README.md is the source of truth for what datasets exist. This script
reads its "### Datasets" list and writes the published page, so the site and the
repo cannot drift: add a dataset to the README and the page follows.

Each dataset is one top-level bullet in that list:

    - [slug](slug/) — description

with optional indented sub-bullets underneath, which become caveat lines. The
intro paragraph above the list and the "### Guidelines" bullets below it are
carried across too.

Run after editing datasets/README.md:

    python3 datasets/build-datasets-page.py

Output (regenerated from scratch, never hand-edited, and gitignored):

  - docs/datasets/index.html

Links point at the dataset folders on GitHub rather than at the site, because
the CSVs are not published to Pages -- only this index is.
"""
import html
import re
from pathlib import Path

DATASETS_DIR = Path(__file__).resolve().parent
DOCS_DIR = DATASETS_DIR.parent / "docs"
SOURCE = DATASETS_DIR / "README.md"
OUTPUT = DOCS_DIR / "datasets" / "index.html"

GENERATED_NOTE = "Generated by datasets/build-datasets-page.py -- do not edit by hand."
REPO_TREE = "https://github.com/jackbandy/data-science-fun/tree/main/datasets"

# `- [slug](slug/) — description`, the shape every dataset bullet has.
ENTRY = re.compile(r"^- \[(?P<slug>[^\]]+)\]\((?P<href>[^)]+)\)\s*[—-]\s*(?P<desc>.+)$")
SUBENTRY = re.compile(r"^\s+[-*]\s+(?P<text>.+)$")
# Inline markdown that shows up in the descriptions: links, then emphasis.
LINK = re.compile(r"\[([^\]]+)\]\(([^)]+)\)")
BOLD = re.compile(r"\*\*([^*]+)\*\*")
ITALIC = re.compile(r"\*([^*]+)\*")
CODE = re.compile(r"`([^`]+)`")


def inline(text: str) -> str:
    """Render the small subset of markdown the README descriptions actually use."""
    out = html.escape(text, quote=False)
    # Code first, so a backticked span cannot be re-processed as emphasis.
    out = CODE.sub(lambda m: f"<code>{m.group(1)}</code>", out)
    out = LINK.sub(lambda m: f'<a href="{html.escape(m.group(2), quote=True)}">{m.group(1)}</a>', out)
    out = BOLD.sub(lambda m: f"<strong>{m.group(1)}</strong>", out)
    out = ITALIC.sub(lambda m: f"<em>{m.group(1)}</em>", out)
    return out


def parse(markdown: str):
    """Pull the intro line, the dataset entries, and the guidelines out of the README."""
    lines = markdown.split("\n")

    # The intro is the first non-empty paragraph under the H1.
    intro = ""
    for i, line in enumerate(lines):
        if line.startswith("# ") and not intro:
            for follow in lines[i + 1:]:
                if follow.strip() and not follow.startswith("#"):
                    intro = follow.strip()
                    break
            break

    entries, guidelines = [], []
    section = None
    for line in lines:
        if line.startswith("###"):
            section = line.lstrip("#").strip().lower()
            continue
        if section == "datasets":
            match = ENTRY.match(line)
            if match:
                entries.append({
                    "slug": match.group("slug"),
                    "href": match.group("href").rstrip("/"),
                    "desc": match.group("desc").strip(),
                    "notes": [],
                })
                continue
            sub = SUBENTRY.match(line)
            if sub and entries:
                entries[-1]["notes"].append(sub.group("text").strip())
        elif section == "guidelines":
            sub = re.match(r"^[-*]\s+(?P<text>.+)$", line)
            if sub:
                guidelines.append(sub.group("text").strip())

    return intro, entries, guidelines


def render(intro: str, entries: list, guidelines: list) -> str:
    items = []
    for entry in entries:
        notes = "".join(
            f'\n    <p class="exercise-item-meta">{inline(n)}</p>' for n in entry["notes"]
        )
        items.append(
            '  <li class="exercise-item">\n'
            f'    <a class="exercise-item-title" href="{REPO_TREE}/{entry["href"]}">{html.escape(entry["slug"])}</a>\n'
            f'    <p class="exercise-item-summary">{inline(entry["desc"])}</p>'
            f'{notes}\n'
            '  </li>'
        )

    guide = ""
    if guidelines:
        bullets = "\n".join(f"  <li>{inline(g)}</li>" for g in guidelines)
        guide = (
            '\n<h2 class="datasets-guidelines-title">Adding a dataset</h2>\n'
            f'<ul class="datasets-guidelines">\n{bullets}\n</ul>\n'
        )

    return f"""---
layout: default
title: Datasets
nav: datasets
description: Datasets used in Introduction to Data Science (CS 418), Fall 2026.
show_last_updated: true
extra_css:
  - /css/exercises.css
---
{{%- comment -%}}
  {GENERATED_NOTE}
  Source: datasets/README.md
{{%- endcomment -%}}

<h1 class="exercises-title">Datasets</h1>
<p class="exercises-subtitle">{inline(intro)}</p>

<p class="exercises-subtitle">{len(entries)} datasets, alphabetical. Each links to
its folder on GitHub, where a README describes the files, columns, sources, and
caveats. The data files themselves are not published to this site &mdash; clone
the repo, or download a file straight from GitHub.</p>

<ul class="exercise-list datasets-list">
{chr(10).join(items)}
</ul>
{guide}
<style>
/* Reuse the exercises card styling, minus its numbering: .exercise-list is
   `list-style: decimal`, which suits a sequence of assignments but would imply
   an order these have -- they are alphabetical, and the count is in the
   subtitle instead. Guidelines get the same measure as the subtitle. */
.datasets-list {{ list-style: none; padding-left: 0; }}
.datasets-guidelines-title {{ margin-top: 2.5rem; }}
.datasets-guidelines {{ max-width: 46rem; line-height: 1.5; }}
.datasets-guidelines li {{ margin-bottom: 0.4rem; }}
</style>
"""


def main() -> None:
    intro, entries, guidelines = parse(SOURCE.read_text(encoding="utf-8"))
    if not entries:
        raise SystemExit(f"no dataset entries found in {SOURCE} -- has the list format changed?")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(intro, entries, guidelines), encoding="utf-8")
    print(f"wrote {OUTPUT} ({len(entries)} datasets, {len(guidelines)} guidelines)")


if __name__ == "__main__":
    main()
