#!/usr/bin/env bash
set -euo pipefail

# lock_requirements.sh — pin the slides' Python packages to the versions the Python Yard runs in the browser.
# Writes pyodide-pins.txt (the Yard's versions of the packages students import) and requirements.lock
# (requirements.txt resolved under those pins), which build_all_quarto.sh and CI install from.
# Run it after editing requirements.txt or bumping jupyterlite-pyodide-kernel in docs/yard/requirements.txt.

SHARED_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
YARD_REQS="$SHARED_DIR/../../yard/requirements.txt"
# The libraries students use in both places; docs/yard/SPECS.md lists the ones the Yard must import.
SHARED=(numpy pandas polars matplotlib scipy statsmodels scikit-learn networkx pyarrow)

KERNEL="$(grep -o 'jupyterlite-pyodide-kernel==[^ ]*' "$YARD_REQS")"
PYODIDE="$(uv run --quiet --no-project --with "$KERNEL" python3 -c 'from jupyterlite_pyodide_kernel.constants import PYODIDE_VERSION; print(PYODIDE_VERSION)')"

{
  echo "# Generated by lock_requirements.sh: the versions Pyodide $PYODIDE ships ($KERNEL in docs/yard/requirements.txt)."
  curl -fsSL "https://cdn.jsdelivr.net/pyodide/v$PYODIDE/full/pyodide-lock.json" | python3 -I -c '
import json, sys
packages = json.load(sys.stdin)["packages"]
for name in sys.argv[1:]:
    print(name + "==" + packages[name]["version"])' "${SHARED[@]}"
} > "$SHARED_DIR/pyodide-pins.txt"

cd "$SHARED_DIR"
uv pip compile --quiet --universal --python-version 3.12 -c pyodide-pins.txt requirements.txt -o requirements.lock
echo "Locked to Pyodide $PYODIDE: $(grep -c '==' requirements.lock) packages in requirements.lock"
